const normalized = (value: string) => value.replace(/\s+/g, " ").trim();
const englishBySource = new Map(Object.entries(english).map(([key, value]) => [normalized(key), value]));
const sourceByEnglish = new Map(Object.entries(english).map(([key, value]) => [normalized(value), key]));
const persianBySource = new Map(Object.entries(persian).map(([key, value]) => [normalized(key), value]));

function translateDynamic(key: string, language: Language): string | undefined {
  if (language === "en") {
    if (key.startsWith("باز کردن ")) return `Open ${key.slice("باز کردن ".length)}`;
    if (key.startsWith("ROI فعال: ")) return `Active ROI: ${key.slice("ROI فعال: ".length)}`;
    if (key.startsWith("صفحهٔ ") && key.includes(" از ")) return key.replace("صفحهٔ ", "Page ").replace(" از ", " of ");
    if (key.startsWith("نام ROI «") && key.endsWith("» تکراری است.")) {
      return `ROI name \"${key.slice(9, -14)}\" is duplicated.`;
    }
    if (key.startsWith("ROI «") && key.endsWith("» حذف شود؟")) {
      return `Delete ROI \"${key.slice(5, -10)}\"?`;
    }
  } else {
    if (key.startsWith("Open ")) return `باز کردن ${key.slice("Open ".length)}`;
    if (key.startsWith("Active ROI: ")) return `ROI فعال: ${key.slice("Active ROI: ".length)}`;
    if (key.startsWith("Page ") && key.includes(" of ")) return key.replace("Page ", "صفحهٔ ").replace(" of ", " از ");
    if (key.startsWith("Delete ROI \"") && key.endsWith("?")) {
      return `ROI «${key.slice(12, -1)}» حذف شود؟`;
    }
  }
  return undefined;
}

export function translateText(value: string, language: Language): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const key = normalized(value);
  const translated = language === "en"
    ? englishBySource.get(key) ?? translateDynamic(key, language)
    : persianBySource.get(key) ?? sourceByEnglish.get(key) ?? translateDynamic(key, language);
  return translated ? `${leading}${translated}${trailing}` : value;
}

type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
};

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = window.localStorage.getItem(storageKey);
    return saved === "en" ? "en" : "fa";
  });

  useEffect(() => {
    window.localStorage.setItem(storageKey, language);
    document.documentElement.lang = language === "fa" ? "fa" : "en";
    document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
    document.documentElement.dataset.language = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      toggleLanguage: () => setLanguage((current) => (current === "fa" ? "en" : "fa")),
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
